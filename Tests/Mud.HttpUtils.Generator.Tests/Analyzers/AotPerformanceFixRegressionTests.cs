/// <summary>
/// 生成器编译期性能修复（方案 v1 §8.3 增量用例清单）的回归测试：
/// F-1 名字键语义与静态缓存隔离、F-2 预筛保守性、F-5 总开关矩阵、F-6 DEBUG 验证跳过开关。
/// </summary>
/// <remarks>
/// 名字键边界直接锚定 <see cref="Mud.HttpUtils.Analyzers.AotDtoCoverageAnalyzer.GetCoverageKey"/> /
/// <see cref="Mud.HttpUtils.Analyzers.AotDtoCoverageAnalyzer.IsCovered(INamedTypeSymbol, HashSet{string})"/>
/// （InternalsVisibleTo 访问，不反射撕开）；缓存隔离与总开关走端到端（Analyze / CompilationWithAnalyzers）。
/// 静态缓存为进程级状态，用例按「不同编译内容 ⇒ 不同 MVID ⇒ 天然隔离」设计，不做测试内清缓存。
