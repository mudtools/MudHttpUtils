    private static ImmutableArray<Diagnostic> RunAotEntryAnalyzers(
        string source, Dictionary<string, string> globalOptions)
    {
        var compilation = CSharpCompilation.Create(
            "SwitchMatrixAssembly",
            new[] { CSharpSyntaxTree.ParseText(source) },
            BasicReferenceAssemblies.GetReferences(),
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary));

        var analyzers = ImmutableArray.Create<DiagnosticAnalyzer>(
            new Mud.HttpUtils.Analyzers.AotDtoCoverageDiagnosticAnalyzer(),
            new Mud.HttpUtils.Analyzers.AotXmlRejectionDiagnosticAnalyzer(),
            new Mud.HttpUtils.Analyzers.HttpJsonSerializableCoverageAnalyzer());

        var analyzerOptions = new AnalyzerOptions(
            ImmutableArray<AdditionalText>.Empty,
            new TestAnalyzerConfigOptionsProvider(globalOptions));

        return compilation
            .WithAnalyzers(analyzers, analyzerOptions)
            .GetAnalyzerDiagnosticsAsync()
            .GetAwaiter()
            .GetResult();
    }

    private static readonly string[] AotDiagnosticIds = { "AOT004", "AOT005", "AOT006", "AOT007" };

    [Fact]
    public void MasterSwitch_False_SilencesAllAotDiagnostics()
    {
        var diagnostics = RunAotEntryAnalyzers(AotProneSource, new Dictionary<string, string>
        {
            ["build_property.PublishAot"] = "true",
            ["build_property.MudEnableAotDiagnostics"] = "false",
        });

        diagnostics.Should().NotContain(d => AotDiagnosticIds.Contains(d.Id),
            "总闸 false 时 AOT004-007 全静默");
    }

    [Fact]
    public void MasterSwitch_Absent_DefaultsToEnabled()
    {
        var diagnostics = RunAotEntryAnalyzers(AotProneSource, new Dictionary<string, string>
        {
            ["build_property.PublishAot"] = "true",
        });

        diagnostics.Should().Contain(d => d.Id == "AOT004",
            "默认（未声明）行为必须与现状一致：未覆盖 DTO 报 AOT004");
        diagnostics.Should().Contain(d => d.Id == "AOT007",
            "默认（未声明）行为必须与现状一致：AOT 模式下 XML 序列化报 AOT007");
    }

    [Fact]
    public void MasterSwitch_False_OverridesCoverageAnalysisOptIn()
    {
        var diagnostics = RunAotEntryAnalyzers(AotProneSource, new Dictionary<string, string>
        {
            ["build_property.PublishAot"] = "true",
            ["build_property.MudEnableAotDiagnostics"] = "false",
            ["build_property.MudEnableAotCoverageAnalysis"] = "true",
        });

        diagnostics.Should().NotContain(d => AotDiagnosticIds.Contains(d.Id),
            "总闸优先于 MudEnableAotCoverageAnalysis（开关矩阵层级）");
    }

    // ───────────────────────── 3.1 DEBUG 验证跳过开关（F-6）─────────────────────────

    [Theory]
    [InlineData(null, false)]
    [InlineData("", false)]
    [InlineData("false", false)]
    [InlineData("0", false)]
    [InlineData("true", true)]
    [InlineData("TRUE", true)]
    [InlineData("1", true)]
    public void GeneratedValidationSkipSwitch_MatchesEnvVar(string? value, bool expected)
    {
        try
        {
            Environment.SetEnvironmentVariable("MudHttpSkipGeneratedValidation", value);
            TransitiveCodeGenerator.ShouldSkipGeneratedValidation().Should().Be(expected);
        }
        finally
        {
            Environment.SetEnvironmentVariable("MudHttpSkipGeneratedValidation", null);
        }
    }

    [Fact]
    public void GeneratedValidationSkipSwitch_DefaultUnset_DoesNotSkip()
    {
        Environment.SetEnvironmentVariable("MudHttpSkipGeneratedValidation", null);
        TransitiveCodeGenerator.ShouldSkipGeneratedValidation().Should().BeFalse(
            "默认行为不变：DEBUG 下仍执行生成代码语法验证");
    }
