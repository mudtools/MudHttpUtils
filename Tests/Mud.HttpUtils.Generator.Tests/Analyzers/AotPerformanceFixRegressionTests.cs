    [Fact]
    public void SyntaxPrefilter_SameTreeAcrossCompilations_ConsistentResult()
    {
        var tree = CSharpSyntaxTree.ParseText(
            """
            namespace N
            {
                public class MarkerHttpClientApiHolder { }
            }
            """);

        Compilation MakeCompilation() => CSharpCompilation.Create(
            "ReuseAssembly_" + Guid.NewGuid().ToString("N"),
            new[] { tree },
            BasicReferenceAssemblies.GetReferences(),
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary));

        var first = SyntaxPrefilter.MayContain(MakeCompilation(), "HttpClientApi");
        var second = SyntaxPrefilter.MayContain(MakeCompilation(), "HttpClientApi");

        first.Should().BeTrue("类型名含标记属误触发，宁误触发不漏报");
        second.Should().Be(first, "同一 SyntaxTree 跨 Compilation 的缓存结果必须一致");
    }

    [Fact]
    public void SyntaxPrefilter_MayHaveAttribute_ShortNameAndQualified_NotMissed()
    {
        var withShortName = ParseTypeDeclaration("""
            using Mud.HttpUtils;

            namespace N
            {
                [HttpJsonSerializable(typeof(int))]
                internal sealed partial class Ctx1 { }
            }
            """);
        var withQualifiedName = ParseTypeDeclaration("""
            namespace N
            {
                [global::Mud.HttpUtils.HttpJsonSerializableAttribute(typeof(int))]
                internal sealed partial class Ctx2 { }
            }
            """);
        var withoutAttribute = ParseTypeDeclaration("""
            namespace N
            {
                internal sealed class Plain { }
            }
            """);

        SyntaxPrefilter.MayHaveAttribute(withShortName, "HttpJsonSerializable").Should().BeTrue(
            "省略 Attribute 后缀的标注不得漏报");
        SyntaxPrefilter.MayHaveAttribute(withQualifiedName, "HttpJsonSerializable").Should().BeTrue(
            "完全限定标注不得漏报");
        SyntaxPrefilter.MayHaveAttribute(withoutAttribute, "HttpJsonSerializable").Should().BeFalse(
            "无标注声明可安全跳过符号绑定（F-2b）");
    }

    private static TypeDeclarationSyntax ParseTypeDeclaration(string source)
    {
        var root = CSharpSyntaxTree.ParseText(source).GetRoot();
        return root.DescendantNodes().OfType<TypeDeclarationSyntax>().First();
    }

    // ───────────────────────── 1.4a 名字键语义（F-1）─────────────────────────

    [Fact]
    public void CoverageKey_ConstructedGenerics_DistinctPerTypeArgument()
    {
        var compilation = CreateShapesCompilation();
        var wrapper = GetShape(compilation, "Shapes.Wrapper`1");
        var foo = GetShape(compilation, "Shapes.Foo");
        var bar = GetShape(compilation, "Shapes.Bar");

        var wrapperOfFoo = AotDtoCoverageAnalyzer.GetCoverageKey(wrapper.Construct(foo));
        var wrapperOfBar = AotDtoCoverageAnalyzer.GetCoverageKey(wrapper.Construct(bar));

        wrapperOfFoo.Should().NotBe(wrapperOfBar,
            "P0 正确性：构造泛型不得坍缩到同一键，否则 List<Foo> 覆盖会被误判为覆盖 List<Bar> → 漏报");

        var covered = new HashSet<string> { wrapperOfFoo };
        AotDtoCoverageAnalyzer.IsCovered(wrapper.Construct(foo), covered).Should().BeTrue();
        AotDtoCoverageAnalyzer.IsCovered(wrapper.Construct(bar), covered).Should().BeFalse(
            "覆盖 Wrapper<Foo> 不得豁免 Wrapper<Bar>");
    }

    [Fact]
    public void CoverageKey_UnboundCoverage_MatchesOpenGenericDefinition()
    {
        var compilation = CreateShapesCompilation();
        var wrapper = GetShape(compilation, "Shapes.Wrapper`1");

        var unboundKey = AotDtoCoverageAnalyzer.GetCoverageKey(wrapper.ConstructUnboundGenericType());
        unboundKey.Should().Contain("Wrapper<>", "注册侧（Scaffolder）以 unbound 形态登记开放泛型");

        var covered = new HashSet<string> { unboundKey };
        AotDtoCoverageAnalyzer.IsCovered(wrapper, covered).Should().BeTrue(
            "开放泛型定义查询侧经 ConstructUnboundGenericType 归一，与 unbound 注册键同键命中");
    }

    [Fact]
    public void CoverageKey_NestedType_DistinctPerEnclosingChain()
    {
        var compilation = CreateShapesCompilation();
        var inner = GetShape(compilation, "Shapes.Outer+Inner");
        var other = GetShape(compilation, "Shapes.Outer+Other");

        var covered = new HashSet<string> { AotDtoCoverageAnalyzer.GetCoverageKey(inner) };
        AotDtoCoverageAnalyzer.IsCovered(inner, covered).Should().BeTrue();
        AotDtoCoverageAnalyzer.IsCovered(other, covered).Should().BeFalse(
            "嵌套类型按完整嵌套链取键，Outer.Inner 覆盖不得豁免 Outer.Other");
    }

    [Fact]
    public void CoverageKey_ValueTuple_ElementNamesIgnored()
    {
        // 元组元素名只能从源符号取（元数据名取不到），经字段类型解析出带名/不带名两种形态。
        var compilation = CreateShapesCompilation();
        var holder = GetShape(compilation, "Shapes.TupleHolder");
        var withNames = holder.GetMembers("WithNames").OfType<IFieldSymbol>().Single().Type;
        var withoutNames = holder.GetMembers("WithoutNames").OfType<IFieldSymbol>().Single().Type;

        AotDtoCoverageAnalyzer.GetCoverageKey(withNames)
            .Should().Be(AotDtoCoverageAnalyzer.GetCoverageKey(withoutNames),
                "ExpandValueTuple：(int a, string) 与 (int, string) 必须同键，避免误报");
    }

    [Fact]
    public void CoverageKey_NullableReferenceModifier_Ignored()
    {
        var compilation = CreateShapesCompilation();
        var foo = GetShape(compilation, "Shapes.Foo");
        var annotated = foo.WithNullableAnnotation(NullableAnnotation.Annotated);

        AotDtoCoverageAnalyzer.GetCoverageKey(annotated)
            .Should().Be(AotDtoCoverageAnalyzer.GetCoverageKey(foo),
                "可空引用修饰符不参与取键（Task<MyDto?> 与 Task<MyDto> 同键）");
    }

    [Fact]
    public void IsCovered_NullableValueType_UnwrapsToInner()
    {
        var compilation = CreateShapesCompilation();
        var intType = compilation.GetSpecialType(SpecialType.System_Int32);
        var nullableOfInt = GetShape(compilation, "System.Nullable`1").Construct(intType);

        var covered = new HashSet<string> { AotDtoCoverageAnalyzer.GetCoverageKey(intType) };
        AotDtoCoverageAnalyzer.IsCovered(nullableOfInt, covered).Should().BeTrue(
            "Nullable<T> 解包后按内层 T 命中");
    }

    [Fact]
    public void IsCovered_CollectionOfCoveredElementType_IsCovered()
    {
        var compilation = CreateShapesCompilation();
        var foo = GetShape(compilation, "Shapes.Foo");
        var listOfFoo = GetShape(compilation, "System.Collections.Generic.List`1").Construct(foo);

        var covered = new HashSet<string> { AotDtoCoverageAnalyzer.GetCoverageKey(foo) };
        AotDtoCoverageAnalyzer.IsCovered(listOfFoo, covered).Should().BeTrue(
            "集合类型解包：元素类型被覆盖即视为覆盖");
    }

    // ───────────────────────── 1.4b 静态缓存 MVID 隔离（F-1）─────────────────────────

    [Fact]
    public void StaticCoveredNamesCache_SameDisplayDifferentContent_ReScans()
    {
        // 两个内容不同、Display 相同的 PE：A 覆盖 RemoteDto、B 不覆盖。
        // 若静态缓存只按 Display 键控（陈旧复用），第二次会误判 RemoteDto 已覆盖 → 漏报。
        var referenceA = EmitContractsReference(contextCoversRemoteDto: true);
        var referenceB = EmitContractsReference(contextCoversRemoteDto: false);

        referenceA.Display.Should().Be(referenceB.Display, "用例前提：两引用 Display 相同");

        AotDtoCoverageAnalyzer.Analyze(BuildApiCompilation(referenceA), CancellationToken.None)
            .Where(d => d.Id == "AOT004")
            .Should().NotContain(d => d.GetMessage(CultureInfo.InvariantCulture).Contains("RemoteDto"),
                "引用 A 的 Context 覆盖 RemoteDto → 不报 AOT004");

        AotDtoCoverageAnalyzer.Analyze(BuildApiCompilation(referenceB), CancellationToken.None)
            .Where(d => d.Id == "AOT004")
            .Should().Contain(d => d.GetMessage(CultureInfo.InvariantCulture).Contains("RemoteDto"),
                "MVID 变化必须触发重扫：引用 B 未覆盖 RemoteDto → 必须报 AOT004");
    }

    private static MetadataReference EmitContractsReference(bool contextCoversRemoteDto)
    {
        var contractsSource = contextCoversRemoteDto ? """
            using System;
            using System.Text.Json;
            using System.Text.Json.Serialization;
            using System.Text.Json.Serialization.Metadata;

            namespace Contracts
            {
                public class RemoteDto { public int Id { get; set; } }

                [JsonSerializable(typeof(RemoteDto))]
                internal sealed partial class ContractsJsonContext : JsonSerializerContext
                {
                    public ContractsJsonContext(JsonSerializerOptions options) : base(options) { }
                    protected override JsonSerializerOptions? GeneratedSerializerOptions => null;
                    public override JsonTypeInfo? GetTypeInfo(Type type) => null;
                }
            }
            """ : """
            using System;
            using System.Text.Json;
            using System.Text.Json.Serialization;
            using System.Text.Json.Serialization.Metadata;

            namespace Contracts
            {
                public class RemoteDto { public int Id { get; set; } }

                [JsonSerializable(typeof(int))]
                internal sealed partial class ContractsJsonContext : JsonSerializerContext
                {
                    public ContractsJsonContext(JsonSerializerOptions options) : base(options) { }
                    protected override JsonSerializerOptions? GeneratedSerializerOptions => null;
                    public override JsonTypeInfo? GetTypeInfo(Type type) => null;
                }
            }
            """;

        var compilation = CSharpCompilation.Create(
            "Contracts",
            new[] { CSharpSyntaxTree.ParseText(contractsSource) },
            BasicReferenceAssemblies.GetReferences(),
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary));

        using var imageStream = new MemoryStream();
        var emitResult = compilation.Emit(imageStream);
        emitResult.Success.Should().BeTrue("合成依赖程序集应能成功编译");

        // 固定 filePath（即 Display）模拟「同路径 PE 原地重建」（IDE 场景 ProjectReference → PE 引用的失效模式）。
        return MetadataReference.CreateFromImage(
            imageStream.ToArray(), MetadataReferenceProperties.Assembly,
            documentation: null, filePath: "Contracts.dll");
    }

    private static Compilation BuildApiCompilation(MetadataReference contractsReference)
    {
        const string apiSource = """
            using System.Threading.Tasks;
            using Mud.HttpUtils.Attributes;

            namespace Api
            {
                [System.Text.Json.Serialization.JsonSerializable(typeof(int))]
                internal sealed partial class ApiJsonContext : System.Text.Json.Serialization.JsonSerializerContext
                {
                    public ApiJsonContext(System.Text.Json.JsonSerializerOptions options) : base(options) { }
                    protected override System.Text.Json.JsonSerializerOptions? GeneratedSerializerOptions => null;
                    public override System.Text.Json.Serialization.Metadata.JsonTypeInfo? GetTypeInfo(System.Type type) => null;
                }

                [HttpClientApi("https://api.example.com")]
                public interface ITestApi
                {
                    [Get("/remote")]
                    Task<Contracts.RemoteDto?> GetRemoteAsync();
                }
            }
            """;

        return CSharpCompilation.Create(
            "ApiAssembly_" + Guid.NewGuid().ToString("N"),
            new[] { CSharpSyntaxTree.ParseText(apiSource) },
            BasicReferenceAssemblies.GetReferences().Append(contractsReference),
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary));
    }

