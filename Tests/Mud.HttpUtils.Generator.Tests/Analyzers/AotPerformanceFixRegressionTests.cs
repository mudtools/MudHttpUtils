public class AotPerformanceFixRegressionTests
{
    private const string ShapesSource = """
        #nullable enable
        namespace Shapes
        {
            public class Foo { }
            public class Bar { }
            public class Wrapper<T> { public T? Value { get; set; } }
            public class Outer
            {
                public class Inner { }
                public class Other { }
            }

            public class TupleHolder
            {
                public (int a, string b) WithNames;
                public (int, string) WithoutNames;
            }
        }
        """;

    private static Compilation CreateShapesCompilation()
    {
        var tree = CSharpSyntaxTree.ParseText(ShapesSource);
        return CSharpCompilation.Create(
            "ShapesAssembly",
            new[] { tree },
            BasicReferenceAssemblies.GetReferences(),
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary));
    }

    private static INamedTypeSymbol GetShape(Compilation compilation, string metadataName)
        => compilation.GetTypeByMetadataName(metadataName)
            ?? throw new InvalidOperationException($"合成形状类型缺失: {metadataName}");

    // ───────────────────────── 1.1 预筛保守性（F-2a / F-2b）─────────────────────────

    [Fact]
    public void SyntaxPrefilter_AliasUsing_NotMissed()
    {
        var source = """
            using JSC = System.Text.Json.Serialization.JsonSerializerContext;
            namespace N
            {
                internal class Fake : JSC { }
            }
            """;
        var compilation = CSharpCompilation.Create(
            "AliasAssembly",
            new[] { CSharpSyntaxTree.ParseText(source) },
            BasicReferenceAssemblies.GetReferences(),
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary));

        SyntaxPrefilter.MayContain(compilation, "JsonSerializerContext").Should().BeTrue(
            "别名 using 的目标标识符 token 含标记，预筛不得漏报");
    }

    [Fact]
    public void SyntaxPrefilter_PartialTypeAcrossTrees_NotMissed()
    {
        var treeWithoutMarker = CSharpSyntaxTree.ParseText(
            """
            namespace N
            {
                internal partial class Split { }
            }
            """);
        var treeWithMarker = CSharpSyntaxTree.ParseText(
            """
            using Mud.HttpUtils.Attributes;

            namespace N
            {
                [HttpClientApi("https://api.example.com")]
                internal partial interface ISplitApi { }
            }
            """);
        var compilation = CSharpCompilation.Create(
            "PartialAssembly",
            new[] { treeWithoutMarker, treeWithMarker },
            BasicReferenceAssemblies.GetReferences(),
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary));

        SyntaxPrefilter.MayContain(compilation, "HttpClientApi").Should().BeTrue(
            "partial 分部声明散落多树时，任一树命中即疑似");
    }

